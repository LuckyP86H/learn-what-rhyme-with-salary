# ---------------------------------------------------------------------------------------------- cli
def _help_of(*cmd: str) -> str:
    proc = subprocess.run([sys.executable, *cmd, "--help"], cwd=ROOT, capture_output=True, text=True, check=True)
    return proc.stdout.rstrip() + "\n"


def cli_md() -> str:
    out = [header("the argparse parsers"), "# Command-line tools\n\n"]
    tools = [
        ("Visualizer: `python -m celery_viz`", ["-m", "celery_viz"], "The monitor itself. In the demo stack the `viz` service runs it with the flags shown in [services](services.md)."),
        ("Spot-eviction simulator: `python3 app/chaos/spot_killer.py`", ["app/chaos/spot_killer.py"], "Runs on the host and shells out to `docker`. Used by `make test-spot`."),
        ("Prefetch experiment: `python3 app/chaos/prefetch_demo.py`", ["app/chaos/prefetch_demo.py"], "Used by `make test-prefetch`."),
        ("Ground-truth check: `python3 scripts/check_viz.py`", ["scripts/check_viz.py"], "Used by `make viz-check`."),
        ("Benchmark: `python scripts/bench_viz.py`", ["scripts/bench_viz.py"], "Used by `make bench-viz`."),
    ]
    for title, cmd, blurb in tools:
        out.append(f"## {title}\n\n{blurb}\n\n```text\n{_help_of(*cmd)}```\n\n")
    return "".join(out)


# ---------------------------------------------------------------------------------------------- make
def make_targets() -> list[tuple[str, str]]:
    rows = []
    for line in (ROOT / "Makefile").read_text().splitlines():
        m = re.match(r"^([a-zA-Z0-9_-]+):.*?## (.*)$", line)
        if m:
            rows.append((m.group(1), m.group(2)))
    return rows


def make_md() -> str:
    out = [header("the `## ` comments in the Makefile"), "# `make` targets\n\n",
           "Run `make help` for the same list in the terminal. Variables such as `CHUNKS=8` or `ID=<call_id>` are noted in each description.\n\n",
           "| Target | What it does |\n|---|---|\n"]
    out += [f"| `make {name}` | {cell(desc)} |\n" for name, desc in make_targets()]
    return "".join(out)


# ---------------------------------------------------------------------------------------------- services
def _load_compose() -> tuple[dict, str]:
    import yaml

    text = (ROOT / "docker-compose.yml").read_text()
    return yaml.safe_load(text), text


def _resolve_port(spec: str) -> tuple[str, str]:
    """'127.0.0.1:${API_PORT:-8100}:8000' -> ('8100', 'API_PORT')"""
    m = re.search(r"\$\{(\w+):-(\d+)\}", spec)
    if m:
        return m.group(2), m.group(1)
    return spec.split(":")[-2], ""


def published_ports() -> set[int]:
    compose, _ = _load_compose()
    ports = set()
    for svc in compose["services"].values():
        for spec in svc.get("ports", []):
            ports.add(int(_resolve_port(str(spec))[0]))
    return ports


def services_md() -> str:
    compose, _ = _load_compose()
    out = [header("docker-compose.yml"), "# Services\n\n",
           "Everything `make up` starts. Host ports are bound to `127.0.0.1` only; override a port with the variable in brackets.\n\n",
           "| Service | What it is | Image | Host port | Command |\n|---|---|---|---|---|\n"]
    for name, svc in compose["services"].items():
        desc = (svc.get("labels") or {}).get("description", "")
        image = svc.get("image", "")
        image = re.sub(r"\$\{(\w+):?-([^}]*)\}", r"\2", image) if image else ""
        if name == "init-db":
            continue
        ports = []
        for spec in svc.get("ports", []):
            port, var = _resolve_port(str(spec))
            ports.append(f"{port}" + (f" (`{var}`)" if var else ""))
        cmd = svc.get("command", "")
        cmd = " ".join(cmd) if isinstance(cmd, list) else str(cmd)
        replicas = (svc.get("deploy") or {}).get("replicas")
        label = f"`{name}`" + (f" ×{replicas}" if replicas else "")
        out.append(f"| {label} | {cell(desc)} | {cell(image) or 'project image'} | {', '.join(ports) or '—'} | {('`' + cell(cmd) + '`') if cmd else '—'} |\n")
    return "".join(out)


# ---------------------------------------------------------------------------------------------- env
def env_md() -> str:
    cfg_src = (ROOT / "config.py").read_text()
    tree = ast.parse(cfg_src)
    # field comments from the Settings dataclass: "    name: type  # comment"
    comments = {m.group(1): m.group(2).strip() for m in re.finditer(r"^\s+(\w+): [^#\n]+#\s*(.+)$", cfg_src, re.M)}
    rows: list[tuple[str, str, str]] = []
    for node in ast.walk(tree):
        if isinstance(node, ast.keyword) and isinstance(node.value, ast.Call):
            # find _env(...) however it is wrapped: float(_env(...)), int(_env(...)), _env(...).upper()
            for sub in ast.walk(node.value):
                if isinstance(sub, ast.Call) and getattr(sub.func, "id", "") in ("_env", "_env_opt") and sub.args and isinstance(sub.args[0], ast.Constant):
                    default = sub.args[1].value if len(sub.args) > 1 and isinstance(sub.args[1], ast.Constant) else ""
                    rows.append((sub.args[0].value, str(default), comments.get(node.arg or "", "")))
                    break
    for extra in ("RELIABILITY_MODE", "CELERY_ACKS_LATE", "CELERY_REJECT_ON_WORKER_LOST", "CELERY_PREFETCH_MULTIPLIER", "QUEUE_TYPE"):
        if not any(r[0] == extra for r in rows):
            rows.append((extra, "", ""))
    seen: set[str] = set()
    unique = [r for r in sorted(rows) if not (r[0] in seen or seen.add(r[0]))]

    _, compose_text = _load_compose()
    compose_vars = []
    for line in compose_text.splitlines():
        for m in re.finditer(r"\$\{(\w+):?-([^}]*)\}", line):
            note = line.split("#", 1)[1].strip() if "#" in line else ""
            compose_vars.append((m.group(1), m.group(2), note))
    seen2: set[str] = set()
    compose_unique = [r for r in compose_vars if not (r[0] in seen2 or seen2.add(r[0]))]

    out = [header("config.py and docker-compose.yml"), "# Environment variables\n\n",
           "## Set when you run `docker compose` / `make`\n\n",
           "Example: `RELIABILITY_MODE=default docker compose up -d --force-recreate worker-spot worker-core`.\n\n",
           "| Variable | Default | Meaning |\n|---|---|---|\n"]
    out += [f"| `{n}` | `{d or '(empty)'}` | {cell(c)} |\n" for n, d, c in compose_unique]
    in_first_table = {n for n, _, _ in compose_unique}
    out += ["\n## Read by the Python code (`config.py`)\n\n",
            "Everything else the code reads. Compose does not set these, so the defaults apply unless you add them to a service's `environment`.\n\n",
            "| Variable | Default | Meaning |\n|---|---|---|\n"]
    out += [f"| `{n}` | `{d or '(unset)'}` | {cell(c)} |\n" for n, d, c in unique if n not in in_first_table]
    return "".join(out)


# ---------------------------------------------------------------------------------------------- modules
def _first_line(text: str | None) -> str:
    for line in (text or "").splitlines():
        line = line.strip()
        if line:
            return line
    return ""


def _describe(path: Path) -> str:
    text = path.read_text()
    if path.suffix == ".py":
        return _first_line(ast.get_docstring(ast.parse(text)))
    if path.suffix == ".sh":
        for line in text.splitlines()[1:6]:
            if line.startswith("#"):
                return line.lstrip("# ").strip()
        return ""
    if path.suffix in (".ts", ".tsx"):
        for line in text.splitlines()[:8]:
            line = line.strip()
            if line.startswith("//"):
                return line.lstrip("/ ").strip()
            if line.startswith("/**"):
                return line.strip("/* ").strip()
        return ""
    if path.name == "states.json":
        return json.loads(text).get("_comment", "")
    return ""


def modules_md() -> str:
    groups = [
        ("Pipeline (Celery app and tasks)", ["config.py", "database.py", "app"], {".py"}),
        ("Visualizer backend (`celery_viz`)", ["celery_viz"], {".py", ".json"}),
        ("Visualizer UI (`viz-ui/src`)", ["viz-ui/src"], {".ts", ".tsx"}),
        ("Scripts", ["scripts"], {".py", ".sh"}),
    ]
    out = [header("the first line of each file's docstring or header comment"), "# Source map\n\n",
           "What each source file is. A blank description means the file has no header comment yet: add one and run `make docs`.\n\n"]
    for title, entries, suffixes in groups:
        files: list[Path] = []
        for entry in entries:
            p = ROOT / entry
            files += [p] if p.is_file() else sorted(q for q in p.rglob("*") if q.is_file() and q.suffix in suffixes)
        files = [f for f in files if "__pycache__" not in f.parts and f.suffix in suffixes and not f.name.endswith((".test.ts", "testkit.ts")) and f.name != "__init__.py"]
        out.append(f"## {title}\n\n| File | What it is |\n|---|---|\n")
        for f in sorted(files):
            rel = f.relative_to(ROOT).as_posix()
            out.append(f"| [`{rel}`](../../{rel}) | {cell(_describe(f))} |\n")
        out.append("\n")
    return "".join(out)


PAGES: dict[str, Callable[[], str]] = {
    "states.md": states_md, "api.md": api_md, "cli.md": cli_md, "make.md": make_md,
    "services.md": services_md, "env.md": env_md, "modules.md": modules_md,
}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="do not write; exit 1 if any generated page is out of date")
    args = ap.parse_args()
    REF.mkdir(parents=True, exist_ok=True)
    stale = []
    for name, build in PAGES.items():
        content = build()
        path = REF / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(name)
        else:
            path.write_text(content)
            print(f"wrote docs/reference/{name}")
    if stale:
        print("stale generated docs: " + ", ".join(stale) + "\nrun: make docs", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
