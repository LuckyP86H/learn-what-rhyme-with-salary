#!/usr/bin/env python3
"""Generate the reference pages in docs/reference/ from the things that are their source of truth.

Reference documentation goes stale the moment someone changes the code and forgets the page, so these
pages are never written by hand:

    states.md    <- celery_viz/states.json          (every task state and what it means)
    api.md       <- the FastAPI apps' OpenAPI        (both HTTP APIs)
    cli.md       <- the argparse parsers             (every command-line flag)
    make.md      <- the Makefile `## ` comments      (every make target)
    services.md  <- docker-compose.yml               (services, ports, commands)
    env.md       <- config.py + docker-compose.yml   (every tunable environment variable)
    modules.md   <- module docstrings                (what each source file is: replaces a file tree)

    python scripts/gen_docs.py          # (re)write the pages           (make docs)
    python scripts/gen_docs.py --check  # fail if any page is stale     (make docs-check, CI)
"""
from __future__ import annotations

import argparse
import ast
import json
import os
import re
import subprocess
import sys
from collections.abc import Callable
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
REF = ROOT / "docs" / "reference"
os.environ["COLUMNS"] = "100"  # argparse wraps help to the terminal width; pin it so output is deterministic
os.environ["NO_COLOR"] = "1"


def header(source: str) -> str:
    return f"<!-- GENERATED by scripts/gen_docs.py from {source}. Do not edit by hand: change the source, then run `make docs`. -->\n\n"


def cell(text: object) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


# ---------------------------------------------------------------------------------------------- states
def states_md() -> str:
    table = json.loads((ROOT / "celery_viz" / "states.json").read_text())
    out = [header("celery_viz/states.json"), "# Task states\n\n"]
    out.append("Every state the visualizer can show, as described in `celery_viz/states.json`. "
               "The UI renders this same data, so this page and the screen cannot disagree.\n\n")
    out.append("**Reported** states are what Celery itself says. **Derived** states (marked `≈` in the UI) are this monitor's "
               "inference from missing or contradictory events; Celery does not report them.\n\n")
    out.append("## Stages\n\nThe columns a task's ball moves through, left to right.\n\n| Stage | Meaning |\n|---|---|\n")
    for st in table["stations"]:
        out.append(f"| {cell(st['label'])} | {cell(st['hint'])} |\n")
    out.append("\n## Overview\n\n| State | Kind | Celery state | Celery event | Stage | Needs attention? |\n|---|---|---|---|---|---|\n")
    stage_name = {s["key"]: s["label"] for s in table["stations"]}
    for s in table["states"]:
        kind = {"celery": "reported", "derived": "derived ≈", "fallback": "fallback"}[s["kind"]]
        out.append(f"| [{cell(s['label'])}](#{s['key'].lower()}) | {kind} | {cell(s['celery']['state'] or '—')} | "
                   f"{cell(s['celery']['event'] or '—')} | {cell(stage_name[s['station']])} | {'**yes**' if s['phase'] == 'attention' else 'no'} |\n")
    out.append("\n## Details\n")
    for s in table["states"]:
        out.append(f"\n### {s['key']}\n\n**{s['label']}** ({'reported by Celery' if s['kind'] == 'celery' else 'derived by this monitor' if s['kind'] == 'derived' else 'fallback'})\n\n")
        out.append(f"{s['summary']}\n\n{s['detail']}\n\n")
        if s["settings"]:
            out.append("Settings that change this:\n\n")
            for setting in s["settings"]:
                out.append(f"- [`{setting['name']}`]({setting['url']}): {setting['why']}\n")
    return "".join(out)


# ---------------------------------------------------------------------------------------------- api
def _schema_fields(spec: dict, schema: dict) -> list[str]:
    if "$ref" in schema:
        schema = spec["components"]["schemas"][schema["$ref"].rsplit("/", 1)[1]]
    required = set(schema.get("required", []))
    rows = []
    for name, prop in schema.get("properties", {}).items():
        kind = prop.get("type") or ("one of " + "/".join(p.get("type", "?") for p in prop.get("anyOf", [])) if prop.get("anyOf") else "object")
        rows.append(f"`{name}` ({kind}{', required' if name in required else ''})")
    return rows


def _openapi_section(title: str, spec: dict) -> str:
    out = [f"## {title}\n\n"]
    for path, methods in spec["paths"].items():
        for method, op in methods.items():
            out.append(f"### `{method.upper()} {path}`\n\n")
            doc = (op.get("description") or op.get("summary") or "").strip()
            out.append(f"{doc}\n\n" if doc else "")
            params = [p for p in op.get("parameters", [])]
            if params:
                out.append("Parameters: " + ", ".join(f"`{p['name']}` ({p['in']}{', required' if p.get('required') else ''})" for p in params) + "\n\n")
            body = op.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
            if body:
                out.append("JSON body: " + "; ".join(_schema_fields(spec, body)) + "\n\n")
    return "".join(out)


